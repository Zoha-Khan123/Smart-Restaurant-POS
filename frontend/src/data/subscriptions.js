/**
 * Calculate KPI summary stats based on live subscriptions dataset
 */
export function calculateSubscriptionStats(subscriptions = []) {
  const total = subscriptions.length;
  const active = subscriptions.filter((s) => s.status === "Active").length;
  const trial = subscriptions.filter((s) => s.status === "Trial").length;
  const expiringSoon = subscriptions.filter(
    (s) => s.status === "Expiring Soon" || (s.daysRemaining > 0 && s.daysRemaining <= 30)
  ).length;
  const expiredOrPastDue = subscriptions.filter(
    (s) => s.status === "Expired" || s.status === "Past Due"
  ).length;

  // Monthly Recurring Revenue calculation
  const totalMRR = subscriptions
    .filter((s) => s.status === "Active" || s.status === "Trial" || s.status === "Expiring Soon")
    .reduce((sum, s) => sum + (s.monthlyEquivalent || 0), 0);

  return {
    totalSubscriptions: total.toString(),
    activeSubscriptions: active.toString(),
    trialSubscriptions: trial.toString(),
    expiringSoon: expiringSoon.toString(),
    expiredOrPastDue: expiredOrPastDue.toString(),
    monthlyRevenue: `$${totalMRR.toLocaleString()}/mo`,
  };
}

