/**
 * Calculate KPI summary stats based on payments dataset
 */
export function calculatePaymentStats(payments = []) {
  const totalRevenue = payments
    .filter((p) => p.paymentStatus === "Paid")
    .reduce((sum, p) => sum + (p.rawTotal || 0), 0);

  // This month's revenue (March 2026 in mock)
  const thisMonthRevenue = payments
    .filter((p) => p.paymentStatus === "Paid" && p.invoiceDate?.startsWith("2026-03"))
    .reduce((sum, p) => sum + (p.rawTotal || 0), 0);

  const pendingPayments = payments
    .filter((p) => p.paymentStatus === "Pending")
    .reduce((sum, p) => sum + (p.rawTotal || 0), 0);
  const pendingCount = payments.filter((p) => p.paymentStatus === "Pending").length;

  const overduePayments = payments
    .filter((p) => p.paymentStatus === "Overdue")
    .reduce((sum, p) => sum + (p.rawTotal || 0), 0);
  const overdueCount = payments.filter((p) => p.paymentStatus === "Overdue").length;

  const failedPayments = payments
    .filter((p) => p.paymentStatus === "Failed")
    .reduce((sum, p) => sum + (p.rawTotal || 0), 0);
  const failedCount = payments.filter((p) => p.paymentStatus === "Failed").length;

  const refundedAmount = payments
    .filter((p) => p.paymentStatus === "Refunded" || (p.refundAmount && p.refundAmount > 0))
    .reduce((sum, p) => sum + (p.refundAmount || p.rawTotal || 0), 0);

  return {
    totalRevenue: `$${totalRevenue.toLocaleString("en-US", { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`,
    thisMonthRevenue: `$${thisMonthRevenue.toLocaleString("en-US", { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`,
    pendingPayments: `$${pendingPayments.toLocaleString("en-US", { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`,
    pendingCount: pendingCount.toString(),
    overduePayments: `$${overduePayments.toLocaleString("en-US", { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`,
    overdueCount: overdueCount.toString(),
    failedPayments: `$${failedPayments.toLocaleString("en-US", { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`,
    failedCount: failedCount.toString(),
    refundedAmount: `$${refundedAmount.toLocaleString("en-US", { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`,
  };
}

