/**
 * Calculates dynamic KPI counts from the restaurant list
 */
export function calculateRestaurantStats(restaurants) {
  const total = restaurants.length;
  const active = restaurants.filter((r) => r.status === "Active").length;
  const inactive = restaurants.filter((r) => r.status === "Inactive").length;
  const pendingPayments = restaurants.filter(
    (r) => r.paymentStatus === "Pending" || r.paymentStatus === "Overdue"
  ).length;

  // Expiring soon is within 30 days or expired
  const expiringSoon = restaurants.filter((r) => {
    if (r.daysLeft === "Expired") return true;
    const days = parseInt(r.daysLeft, 10);
    return !isNaN(days) && days <= 30;
  }).length;

  return [
    {
      id: "total-restaurants",
      title: "Total Restaurants",
      value: total.toString(),
      change: "+14.2%",
      changeType: "increase",
      subtext: "vs. last month",
      icon: "Store",
      cardBg: "bg-blue-600",
      iconBg: "bg-blue-500/30",
    },
    {
      id: "active-restaurants",
      title: "Active Restaurants",
      value: active.toString(),
      change: `${total > 0 ? ((active / total) * 100).toFixed(0) : 0}%`,
      changeType: "increase",
      subtext: "active rate",
      icon: "ShieldCheck",
      cardBg: "bg-emerald-600",
      iconBg: "bg-emerald-500/30",
    },
    {
      id: "inactive-restaurants",
      title: "Inactive Restaurants",
      value: inactive.toString(),
      change: `${inactive} inactive`,
      changeType: inactive > 0 ? "warning" : "neutral",
      subtext: "attention",
      icon: "AlertTriangle",
      cardBg: "bg-amber-600",
      iconBg: "bg-amber-500/30",
    },
    {
      id: "pending-payments",
      title: "Pending Payments",
      value: pendingPayments.toString(),
      change: `${pendingPayments} pending`,
      changeType: pendingPayments > 0 ? "warning" : "neutral",
      subtext: "invoices",
      icon: "Clock",
      cardBg: "bg-rose-600",
      iconBg: "bg-rose-500/30",
    },
    {
      id: "expiring-soon",
      title: "Expiring Soon",
      value: expiringSoon.toString(),
      change: "≤ 30 days",
      changeType: "neutral",
      subtext: "renewals",
      icon: "Zap",
      cardBg: "bg-purple-600",
      iconBg: "bg-purple-500/30",
    },
  ];
}
