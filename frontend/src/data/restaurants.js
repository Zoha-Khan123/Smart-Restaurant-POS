    restaurant.subscriptionPlan === "Premium"
      ? "$199.00"
      : restaurant.subscriptionPlan === "Standard"
      ? "$79.00"
      : "$29.00";

  const isOverdue = restaurant.paymentStatus === "Overdue";
  const isPending = restaurant.paymentStatus === "Pending";

